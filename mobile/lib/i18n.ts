// obj carries bilingual pairs like name/name_en, specialization/specialization_en -
// matches the influencers table's *_en columns (supabase/migrations/003_add_en_columns.sql).
export function translateField(obj: Record<string, any>, field: string, lang: Lang): string {
  if (lang === 'en' && obj[`${field}_en`]) return obj[`${field}_en`]
  return obj[field] || ''
}

export function translateList(obj: Record<string, any>, field: string, lang: Lang): string[] {
  if (lang === 'en' && obj[`${field}_en`]?.length) return obj[`${field}_en`]
  return obj[field] || []
}

// getTier() (lib/api.ts) always returns the Arabic tier name - this maps it
// to the matching dictionary key so tier badges can display in English too.
const TIER_KEYS: Record<string, TKey> = {
  'نانو': 'nano',
  'ميكرو': 'micro',
  'ماكرو': 'macro',
  'ميجا': 'mega',
  'ألفا': 'alpha',
}

export function translateTier(tierAr: string, lang: Lang): string {
  const key = TIER_KEYS[tierAr]
  return key ? translate(key, lang) : tierAr
}

